# --- phase timing summary (PRD-build-gate-phase-timing) -------------------
# Builds `phases=<name>:<val>,...` in invocation order from the
# record_phase calls above, and checks the sum of every non-skipped phase's
# seconds (a fail's own `!`-suffixed seconds still count toward the sum —
# only `skip` is excluded, requirement: "a phase that fails or is skipped
# is recorded as such, never as zero") against `wall` within 5%; anything
# wider is surfaced as `unattributed:<s>` rather than silently dropped
# (requirement: "the sum of phase seconds is within 5% of wall or the line
# carries unattributed:<s>").
phases_str=""
phase_sum=0
for _pi in "${!phase_names[@]}"; do
  _pname="${phase_names[$_pi]}"
  _pval="${phase_vals[$_pi]}"
  case "$_pval" in
    skip)  : ;;
    defer) : ;;
    *!)    phase_sum=$(( phase_sum + ${_pval%!} )) ;;
    *)     phase_sum=$(( phase_sum + _pval )) ;;
  esac
  if [ -n "$phases_str" ]; then phases_str="$phases_str,$_pname:$_pval"; else phases_str="$_pname:$_pval"; fi
done
phase_unattributed=$(( wall - phase_sum ))
[ "$phase_unattributed" -lt 0 ] && phase_unattributed=0
phase_tolerance=0
[ "$wall" -gt 0 ] && phase_tolerance=$(( wall * 5 / 100 ))
phase_over_tolerance=false
phases_field="phases=$phases_str"
if [ "$phase_unattributed" -gt "$phase_tolerance" ]; then
  phase_over_tolerance=true
  phases_field="$phases_field,unattributed:$phase_unattributed"
fi

# --- attribution (P0 requirement 1, PRD-build-gate-debt-auto-prd; diff
# range widened by PRD-build-inherited-blocks-delta-pass requirement 2) ---
# Split blocking_notes into in-scope (the building PRD's own diff touched
# it) vs inherited (landed by an earlier merge). The diff range:
#   - HEAD is a no-ff merge commit (two parents, the post-land case) ->
#     <head>^1..<head> exactly — the merge's first parent is mainline
#     immediately before this PRD landed, so the diff against it is what
#     the PRD's own merge introduced ("for main scope after a landing it
#     is the landing's own merge range").
#   - `--scope branch` (an un-landed branch gate, in its own worktree) ->
#     `git merge-base <main-at-gate-start> <head>`..<head> — requirement
#     2's literal "merge-base(main, branch)..branch": main_sha_at_gate_start
#     (set above, PRD-build-gate-before-land) is this run's own reading of
#     main's tip, so the merge-base against it is exactly that.
#   - anything else (a `--scope main` run ahead of any merge, e.g. a fresh
#     repo) -> the wider $base_ref..HEAD range — less surgical, but never
#     crashes attribution into treating an unlanded main's own changes as
#     "no diff at all".
attribution_json=""
attribution_inherited=0
attribution_in_scope=0
attribution_unknown_inputs=0
attribution_baseline_witness=0
attribution_commit_range=0
# Which rule chose attr_diff_base below. Only ever set to a non-empty value
# by the --pinned-landing branch (requirement 2's main-scope clause); the
# empty default means "the pre-existing base_ref/merge-base/merge-parent
# rules picked the range", which is journaled as nothing at all so every
# non-landing gate line stays byte-identical to before this PRD.
attribution_range_source=""
if [ "${#blocking_notes[@]}" -gt 0 ] && [ -x "$GATE_ATTRIBUTION" ]; then
  attr_diff_base="$base_ref"
  if [ "$scope" = branch ] && [ -n "${main_sha_at_gate_start:-}" ]; then
    attr_diff_base="$(git -C "$repo" merge-base "$main_sha_at_gate_start" "$head_now" 2>/dev/null || echo "$main_sha_at_gate_start")"
  fi
  parent_count="$(git -C "$repo" rev-list --parents -n1 "$head_now" 2>/dev/null | awk '{print NF-1}')"
  if [ "${parent_count:-0}" -eq 2 ]; then
    attr_diff_base="${head_now}^1"
  fi
  # PRD-build-inherited-blocks-delta-pass requirement 2, the main-scope
  # clause: "for main scope after a landing it is the landing's OWN merge
  # range (state/landings/<repo>/<slug>.json)". The two-parent case above
  # already lands that range for a genuine merge commit (M^1..M), but
  # gate-then-land.sh also lands via `--squash`, and a squash/fast-forward
  # landing is a ONE-parent commit: it misses the branch above and falls
  # all the way back to $base_ref, which resolve_base() sets to the newest
  # reachable VERSION TAG — a range spanning every landing since that tag,
  # not this one. A too-wide range is the dangerous direction for THIS
  # PRD specifically: every path any other landing touched enters
  # diff_files, so blocks this landing genuinely inherited get scored
  # in-scope, under-reporting the inherited set that requirement 4
  # (gate-debt drafting) and requirement 7 (the weekly inherited-debt
  # line) are both computed from. Requirement 6 keeps main-scope VERDICTS
  # off attribution, so this only ever moves the journal's
  # inherited=/in-scope= tokens and the debt accounting downstream of
  # them — never a pass/block decision.
  #
  # So under --pinned-landing, pin the range to the landing record the PRD
  # names. `merge_sha` is the field landing-verdict-resolve.sh reads first;
  # `head_sha` is the pre-merge fallback every record has carried since
  # branch-protection.sh started writing them. Resolution is deliberately
  # local-only (no gh, no fetch — a gate must not grow a network
  # dependency here); anything unresolvable leaves attr_diff_base exactly
  # as the lines above left it, so this is strictly a narrowing fix.
  # BEGIN inhblocks-r2-landing-range (tests/inhblocks_p0_acs.sh extracts
  # this exact block by marker and evals it — keep it self-contained: it
  # reads only pinned_landing/STATE_DIR/repo/slug and writes only
  # attr_diff_base/attribution_range_source, all already defined above.)
  if $pinned_landing; then
    _attr_landing_rec="$STATE_DIR/landings/$(repo_slug_for_ci "$repo")/${slug}.json"
    if [ -r "$_attr_landing_rec" ]; then
      _attr_landing_sha="$(python3 -c 'import json,sys
try:
    d = json.load(open(sys.argv[1]))
except Exception:
    raise SystemExit(0)
print(d.get("merge_sha") or d.get("head_sha") or "")' "$_attr_landing_rec" 2>/dev/null)"
      if [ -n "${_attr_landing_sha:-}" ] \
        && git -C "$repo" rev-parse --verify --quiet "${_attr_landing_sha}^{commit}" >/dev/null 2>&1 \
        && git -C "$repo" rev-parse --verify --quiet "${_attr_landing_sha}^1^{commit}" >/dev/null 2>&1; then
        attr_diff_base="${_attr_landing_sha}^1"
        attribution_range_source="landing-record"
      fi
    fi
  fi
  # END inhblocks-r2-landing-range
  attr_notes_file="$(mktemp "${TMPDIR:-/tmp}/extend-gate-attr-notes.XXXXXX")"
  for n in "${blocking_notes[@]}"; do
    # note_block strings are always "<receipt> — <detail>" (em dash,
    # consistent across every note_block call above); split on the first
    # occurrence so a detail that itself contains " — " stays intact.
    printf '%s\n' "$n" | sed -E 's/^([^ ]+) — (.*)$/\1\t\2/' >> "$attr_notes_file"
  done
  if attr_out="$("$GATE_ATTRIBUTION" compute "$repo" "$attr_diff_base" "$head_now" "$attr_notes_file" 2>/dev/null)"; then
    attribution_json="$attr_out"
    attribution_in_scope="$(python3 -c 'import json,sys; print(json.loads(sys.argv[1]).get("in_scope",0))' "$attribution_json" 2>/dev/null || echo 0)"
    attribution_inherited="$(python3 -c 'import json,sys; print(json.loads(sys.argv[1]).get("inherited",0))' "$attribution_json" 2>/dev/null || echo 0)"
    attribution_unknown_inputs="$(python3 -c 'import json,sys; print(json.loads(sys.argv[1]).get("unknown_inputs",0))' "$attribution_json" 2>/dev/null || echo 0)"
    attribution_baseline_witness="$(python3 -c 'import json,sys; print(json.loads(sys.argv[1]).get("baseline_witness",0))' "$attribution_json" 2>/dev/null || echo 0)"
    attribution_commit_range="$(python3 -c 'import json,sys; print(json.loads(sys.argv[1]).get("commit_range",0))' "$attribution_json" 2>/dev/null || echo 0)"
  fi
  rm -f "$attr_notes_file"
fi
# $journal was resolved (and the selftest isolation guard applied) right
# after $head_now above, PRD-build-gate-before-land requirement 4 — the
# verdict-cache-hit early-exit needs it too now, so it moved earlier
# instead of being duplicated. Kept as a no-op here (mkdir -p is
# idempotent) in case a future edit reorders things again.
mkdir -p "$(dirname "$journal")"

