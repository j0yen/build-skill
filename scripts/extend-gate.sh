# had no blocking notes, or gate-attribution.sh wasn't runnable — the
# summary receipt always has the key, never sometimes-present (requirement
# 1: "the tags land in the summary receipt").
attribution_empty='{"blocks":[],"in_scope":0,"inherited":0}'
attribution_for_cache="${attribution_json:-$attribution_empty}"
# PRD-build-inherited-blocks-delta-pass requirement 5 (P1, AC7): the diff
# range attribution actually used this run, one value for every block in
# it (attribution computes ONE range per run, not per-finding) — read by
# --explain-verdict below. Empty/empty when attribution never ran.
attribution_range_base="${attr_diff_base:-}"
attribution_range_head="${head_now:-}"
[ -n "$attribution_json" ] || attribution_range_head=""
# Phase timing (PRD-build-gate-phase-timing requirement: "the gate receipt
# ... gains a phases object with the same values plus wall_s and head") —
# built from the same phase_names/phase_vals arrays the journal line's
# phases_field above reads, so receipt and journal never disagree.
phases_json='{}'
for _pi in "${!phase_names[@]}"; do
  phases_json="$(jq -c --arg k "${phase_names[$_pi]}" --arg v "${phase_vals[$_pi]}" '. + {($k): $v}' <<<"$phases_json")"
done
jq -n --arg head "$head_now" --arg tree "$tree_now" --arg hash "$self_hash" --arg verdict "$cache_verdict_val" \
     --argjson rc "$final_rc" --arg new "$new_blocks" --arg inh "$inherited_blocks" \
     --arg intended "$route_intended" --argjson burst "$route_burst_n" \
     --argjson local "$route_local_n" --argjson passthrough "$route_passthrough_n" \
     --arg host "$route_host" --argjson attribution "$attribution_for_cache" \
     --argjson phases "$phases_json" --argjson wall_s "$wall" \
     --arg scope "$scope" --arg slug "$slug" \
     --argjson deferred "$deferred_json" \
     --arg gate_route "$GATE_ROUTE" --argjson routed_n "$routed_n" --argjson receipts_total "$receipts_total" \
     --argjson over "$phase_over_tolerance" --argjson unattr "$phase_unattributed" \
     --argjson infra "$infra_notes_json" \
     --arg attr_base "$attribution_range_base" --arg attr_head "$attribution_range_head" '
  {
    head_sha: $head,
    head: $head,
    tree_sha: $tree,
    script_sha256: $hash,
    verdict: $verdict,
    exit_code: $rc,
    new_blocks: ($new | if . == "" then [] else split(",") end),
    inherited_blocks: ($inh | if . == "" then [] else split(",") end),
    cargo_route: {intended: $intended, burst: $burst, local: $local, passthrough: $passthrough, host: $host},
    route: $gate_route,
    routed: {n: $routed_n, receipts: $receipts_total},
    blocks: $attribution.blocks,
    attribution: {in_scope: $attribution.in_scope, inherited: $attribution.inherited},
    attribution_range: (if $attr_head == "" then null else {base: $attr_base, head: $attr_head} end),
    phases: $phases,
    wall_s: $wall_s,
    scope: $scope,
    slug: $slug,
    deferred_receipts: $deferred,
    infra_notes: $infra
  } + (if $over then {unattributed_s: $unattr} else {} end)
' > "$cache_file" 2>/dev/null || true

# R4 persist-out: a fresh run (producers actually ran) writes cache_file
# above — mirror it out too, same as the cache-hit replay path does,
# so a pinned-landing caller's NEXT question for this slug (a brand new
# detached worktree, per main-verdict-pin-gate.sh's own header) has a
# mirror to seed from instead of paying this same full run again.
if [ -n "$verdict_cache_mirror" ]; then
  mkdir -p "$(dirname "$verdict_cache_mirror")" 2>/dev/null && cp "$cache_file" "$verdict_cache_mirror" 2>/dev/null || true
fi

# --- best-effort: merge cargo_route into autobuilder's own release
# receipt too (target/autobuilder/receipts/<head_sha>.json — gate.rs's
# ReceiptPath::HeadShaJson), when the `autobuilder gate` run above actually
# wrote one, so a reviewer reading the receipt directly (not just
# last-verdict.json) sees the same attestation (P0 requirement 3). autobuilder
# itself is a separate crate this PRD's Engineering target does not touch —
# this is a non-destructive jq merge onto whatever it already wrote, never a
# schema change, and fails open (never blocks the gate) if the file is
# absent or jq can't merge it.
release_receipt="$project_abs/target/autobuilder/receipts/${head_now}.json"
if [ -f "$release_receipt" ]; then
  release_receipt_tmp="$(mktemp "${TMPDIR:-/tmp}/extend-gate-receipt.XXXXXX")"
  if jq --arg intended "$route_intended" --argjson burst "$route_burst_n" \
        --argjson local "$route_local_n" --argjson passthrough "$route_passthrough_n" \
        --arg host "$route_host" \
        '. + {cargo_route: {intended: $intended, burst: $burst, local: $local, passthrough: $passthrough, host: $host}}' \
        "$release_receipt" > "$release_receipt_tmp" 2>/dev/null; then
    mv "$release_receipt_tmp" "$release_receipt"
  else
    rm -f "$release_receipt_tmp"
  fi
fi

exit "$final_rc"
