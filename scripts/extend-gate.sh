GATE_WEDGE_SH="${GATE_WEDGE_SH:-$BUILD_SCRIPTS/gate-wedge.sh}"
EXTEND_GATE_LOOP_WALL_S="${EXTEND_GATE_LOOP_WALL_S:-1800}"
GATE_WEDGE_STATE_DIR="${GATE_WEDGE_STATE_DIR:-$BUILD_SCRIPTS/../state/gate-wedge}"
cargo_budgeted() {
  # Retained for any DIRECT `cargo test`/`clippy`/`deny` call this gate
  # makes itself (none today — see run_unslotted_producer() below for
  # where the two producer-phase call sites moved to,
  # PRD-build-cargo-budget-per-invocation requirement 1). Fails open
  # (never blocks the gate) if burst-lane.sh or cargo-budget.sh is
  # missing — this gate must still run against whatever is on disk
  # rather than turn a missing helper into a gate outage.
  if [ -x "$BURST_LANE_SH" ]; then
    "$BURST_LANE_SH" ensure-fresh "$repo" >/dev/null 2>&1 || true
  fi
  if [ -x "$CARGO_BUDGET" ]; then
    "$CARGO_BUDGET" run -- "$@"
  else
    "$@"
  fi
}
# PRD-build-cargo-budget-per-invocation requirement 1: a producer phase
# (the proof-receipt loop's `autobuilder loop`, extended-receipts.sh's 17
# producers) no longer takes ONE cargo-budget slot for its whole phase —
# that let an agent-driven, mostly-idle phase hold a slot for up to an
# hour (the 2026-09-13 incident: one hold at peak_load=0.83, no compiler
# running, while 20 other cargo invocations elsewhere timed out on the 2
# slots this budgets). Instead the producer runs UNSLOTTED, with the SAME
# PATH prefix cargo_route_path_prefix() gives the guard above FIRST on
# $PATH (so every real `cargo test`/`clippy`/`deny`/`nextest`/`build
# --release` call it shells to takes its own slot for exactly its own
# duration — see cargo-budget.sh — and, when burst is configured, still
# gets a chance to route to the box) and CARGO_BUDGET_PARENT_STEP set so
# each of those slots' ledger rows records which producer spawned it.
# PRD-build-cargo-route-precedence requirement 2: this MUST be the same
# prefix burst-lane.sh's route-check attests against (both call the same
# helper) — a producer PATH that drifted from what the probe checks is
# exactly how the 2026-09-15 defect went unnoticed. The `VAR=val PATH=...
# cmd` prefix form here scopes both to this one command's own process
# tree — it never mutates this script's own $PATH/env for any later phase.
run_unslotted_producer() {  # $1=parent-step name, then the producer command
  local step="$1"; shift
  if [ -x "$BURST_LANE_SH" ]; then
    "$BURST_LANE_SH" ensure-fresh "$repo" >/dev/null 2>&1 || true
  fi
  PATH="$(cargo_route_path_prefix 2>/dev/null || echo "$BUILD_SCRIPTS/cargo-budget-bin"):$PATH" \
    CARGO_BUDGET_PARENT_STEP="$step" "$@"
}

die() { echo "extend-gate: $2" >&2; exit "$1"; }

usage() {
  cat <<'EOF'
usage: extend-gate.sh <build_into> [--base <tag>] [--head <sha>] [--dry-run]
                       [--parallelism N] [--record-baseline] [--force]
                       [--phases-json] [--print-verdict-path]
                       [--scope main|branch --slug <slug>]
       extend-gate.sh --explain-scope
EOF
}

# PRD-build-branch-gate-scope-artifacts requirement 9 (P2, AC11): a
# standalone, argument-free print of the branch-scope policy table below —
# so "what does branch scope do to producer X" is one command, not a
# read of this file's own comments (requirement 1/2/3/5's inline notes at
# the rollback-plan, ci-checks, reviewer-agent, and land call sites).
explain_scope() {
  cat <<'EOF'
producer          branch-scope policy
----------------  -----------------------------------------------------
risk-gate         unchanged (runs identically at any scope, if scripts/audit.sh exists)
intake            unchanged
proof-receipt     unchanged (autobuilder loop --iteration 0 --trace)
vti-plan          unchanged
rollback-plan     a head-untagged block on THIS run's own fresh HEAD is
                  post-classified scope-deferred (never blocking) — a
                  branch HEAD never carries a release tag; any other
                  block_reason still blocks. land re-runs this producer
                  at --scope main before tagging.
reviewer-agent    always runs at branch scope (the quota-guard skip that
                  suppresses a doomed main-scope gate does not apply
                  here — a branch's reviewer finding is wanted whether
                  the branch passes or blocks); at --scope main,
                  unchanged (skipped when any in-scope block exists).
ci-checks         BRANCH_GATE_PUSH=1 (default): pushes the branch to
                  origin under its own ref, waits up to
                  CI_CHECKS_BRANCH_WAIT (default 900s) for a run to
                  appear; run_count==0 after the wait -> scope-deferred
                  (no-runs-on-ref). BRANCH_GATE_PUSH=0: never invoked,
                  scope-deferred (push-disabled). A push failure ->
                  scope-deferred (push-failed). Any OTHER outcome
                  (a real run that failed/is pending) still blocks.
                  land re-runs this producer at --scope main.
extended-receipts unchanged (17 producers, run in parallel)
gate              unchanged (autobuilder gate reads all receipts fresh
                  off disk; a scope-deferred receipt was already
                  rewritten to pass before this runs, so it never sees
                  the deferral as a block)
land              (not a gate producer) re-runs every scope-deferred
                  producer named above at --scope main on the landed
                  head before cutting a tag; a block there is a normal
                  main-scope block (branch stays merged, main untagged).
EOF
}

if [ "${1:-}" = "--explain-scope" ]; then
  explain_scope
  exit 0
fi

# PRD-build-gate-patience-from-queue-depth requirement 3 (P0, AC5): prints
# the live holder's identity (pid, slug, scope, age) from the `.holder`
# sidecar file written beside whichever lock this <build_into>/--scope
# would take — the exact thing a `contended` journal line already names,
# available on demand without grepping the journal. Exit 1 + "no holder
# (lock free)" when the sidecar is absent (lock free, or a pre-this-PRD
