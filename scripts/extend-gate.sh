#!/usr/bin/env bash
# extend-gate.sh — regenerate autobuilder's 25 receipts at HEAD on a
# rust-extend crate's main checkout, so the deploy gate a rust-extend ship
# reads is never bound to a stale commit. PRD-build-extend-gate-receipts.
#
# usage: extend-gate.sh <build_into> [--base <tag>] [--head <sha>] [--dry-run]
#                        [--project-root <rel>]
#                        [--parallelism N] [--record-baseline] [--force]
#                        [--phases-json]
#
# Phase timing (PRD-build-gate-phase-timing): every producer step below is
# individually timed (never restructured — same order, same pass/block
# contribution). The journal line's `wall=<s>s` gains a
# `phases=<name>:<s>,...` field right after it, in invocation order; a step
# this run never invoked (no scripts/audit.sh, gh unavailable, reviewer
# bypassed by a prior block) reads `<name>:skip`, and a step whose own
# subprocess exited non-zero reads `<name>:<s>!` — never a silent `:0`. The
# same breakdown, plus `wall_s` and `head`, lands in the cached verdict
# receipt (target/autobuilder/last-verdict.json) under a `phases` key.
# `--phases-json` is a read-only mode: prints that cached `{phases,
# wall_s, head}` for <build_into>'s last gate and exits 0 — no producer
# runs, no lock taken, nothing journaled. `--print-verdict-path`
# (PRD-build-gate-before-land requirement 3) is the same read-only class:
# resolves and prints the verdict-cache path (the exact
# target/autobuilder/last-verdict.json a real run at <build_into> would
# read/write, honoring --project-root / find_cargo_root the same way) and
# exits 0 — the rebase-and-regate loop's way of locating the file to pass
# as `worktree-extend.sh land --verdict <path>` without duplicating the
# project-root search.
#
# On a clean main checkout, at HEAD, in this order:
#   scripts/audit.sh                         (if the crate has one)
#   intent-card-refresh.sh --prd <this branch's own PRD>   (--scope branch
#     only, PRD-build-intent-card-pregate-refresh — refreshes and commits
#     agent/intent-card.json BEFORE intake/reviewer-agent below ever read
#     it, so a branch is never judged against main's last-refreshed card;
#     a resolution/lint failure blocks with `intent-card-stale (cause=...)`
#     and skips reviewer-agent entirely — see that block's own comments)
#   autobuilder intake --validate agent/intent-card.json --project <root>
#     (writes receipts/intake.json fresh at HEAD — PRD-build-gate-producers;
#     before that PRD, nothing in this sequence ever passed --project, so
#     intake.json was never regenerated by a live gate run)
#   autobuilder loop --project <root> --iteration 0 --head-sha <HEAD> --trace
#   autobuilder vti-plan
#   autobuilder rollback-plan --base <base>
#   autobuilder reviewer-agent prepare --base <base>, then finalize
#     (the binary cannot spawn its own subagent — see
#     autobuilder/src/reviewer.rs — so this script spawns a headless
#     sonnet review via `claude -p` and feeds its JSON to finalize)
#   autobuilder ci-checks
#   ~/.claude/skills/rustbuild/scripts/extended-receipts.sh <root> [parallelism]
#   autobuilder gate --project <root>
# <root> is normally <build_into> itself, but is resolved to the nearest
# subdirectory containing Cargo.toml when <build_into> has none at its own
# root (see "cargo project root resolution" below).
# <base> defaults to the newest `v<major>.<minor>.<patch>` tag reachable
# from HEAD by first-parent (autobuilder's own rollback-plan convention),
# falling back to the crate's initial commit when no such tag exists.
#
# Prints the gate's own summary line (`gate: head=... pass=N block=M
# verdict=...`) and exits with the gate's verdict.
#
# Delta verdict against a committed baseline (PRD-build-gate-delta-baseline).
# `autobuilder gate`'s own pass/block is not the final word: this script
# additionally diffs the blocking receipt set against
# `<build_into>/agent/gate-baseline.json` AT HEAD (a working-tree-only copy
# never counts — fail closed) via `scripts/gate-delta.sh verdict`, and
# prints its own summary line:
#   extend-gate: delta verdict=pass|delta-pass|block baseline=present|absent new_blocks=<...> inherited_blocks=<...>
# `delta-pass` means block>0 but every blocking receipt name is already in
# the baseline — this script then exits 0 (shippable), same as a plain
# `pass`. `block` means at least one blocking receipt is NOT in the
# baseline (or there is no committed baseline at all — today's behavior,
# preserved byte-for-byte: no baseline means this new summary line and the
# exit code are unaffected by anything above). `--record-baseline` writes
# the baseline from the CURRENT run's blocking set instead of computing a
# verdict against one — see that flag's own note below. A verdict run
# never writes or widens the baseline itself.
#
# <build_into> is normally both the git repo root and the Cargo project
# root (mcphost, wm-node, adopt) — but that's not universal. When the repo
# root has no Cargo.toml (rustbuild's has always lived one level down, at
# autobuilder/Cargo.toml), immediate subdirectories are searched (depth 1,
# then depth 2 if depth 1 finds nothing — never descending into target/ or
# .git/) for exactly one Cargo.toml, and THAT resolved path is passed to
# every producer below (including extended-receipts.sh's 17) instead of
# the repo root, so cargo-invoking producers stop exiting 101 for "could
# not find Cargo.toml" against a directory that was never the actual
# crate. A repo with a root Cargo.toml AND a nested one keeps the root,
# unchanged (no search triggered). Ambiguous (>1 candidate) or absent (0
# candidates) fails loudly (exit 6) naming what was searched, before any
# producer runs — never a silent 101. PRD-build-extend-gate-nested-crate-project.
#
# Exit codes:
#   0  gate verdict pass (pass=25 block=0) OR delta-pass (block>0 but every
#      blocking receipt is in the committed baseline) OR a successful
#      `--record-baseline` write (that mode's exit code reports the write,
#      not the underlying pass/block)
#   1  gate verdict block (one or more receipts failed, and at least one
#      of them is not in the committed baseline — or there is no committed
#      baseline at all)
#   1  usage error (bad/missing arguments)
#   2  a required binary is missing from $PATH (autobuilder, extended-receipts.sh,
#      ship-tag.sh, gate-delta.sh, jq) — cannot even attempt a run
#   3  dirty tree — refused before any producer ran, nothing under
#      target/autobuilder/ changed
#   4  could not acquire the per-repo integration lock within
#      $EXTEND_GATE_PRODUCER_LOCK_WAIT seconds (default 90 — PRD-build-
#      extend-gate-concurrent-isolation requirement 2). The message names
#      the contending pid(s) ("producer-lock-contended, pid=<n>[,<n>...]"),
#      is refused before any producer ran, and never emits a `gate: ...
#      pass=.../block=...` verdict line — fail-closed, not fail-wrong.
#   5  --head <sha> (abbreviated SHAs accepted — resolved via `git
#      rev-parse --verify <sha>^{commit}` and compared full-SHA-to-
#      full-SHA) does not resolve, or resolves to something other than
#      actual HEAD — refused before any producer ran
#   6  could not resolve a unique Cargo project root under <build_into>
#      (none found, or more than one candidate) — refused before any
#      producer ran
#   7  installed `autobuilder` binary is STALE — its `--version` is older
#      than the canonical crate's `[package] version` in
#      $AUTOBUILDER_CANONICAL_CARGO_TOML — refused before any producer ran
#      (AC4, PRD-autobuilder-source-unify). The message names the
#      installed version, the expected (canonical) version, and the exact
#      `cargo install --path <canonical-crate-dir> --locked` fix. Skipped
#      (not an error) when the canonical Cargo.toml itself is absent —
#      e.g. a test HOME with no checked-out canonical crate — since this
#      guard is about staleness, not about requiring the canonical source
#      to exist on every box that runs a gate.
#   8  cargo route mismatch that self-heal could not fix — burst was
#      intended (a session is up) but no cargo shim is reachable on this
#      process's own $PATH even after burst-lane.sh route-check tried
#      prepending the correct prefix (PRD-build-cargo-route-precedence,
#      requirement 3) — refused before any producer ran, rather than
#      running the whole producer sequence locally and reporting a
#      verdict that never touched the box it was supposed to.
#   9  gate verdict incomplete (PRD-build-gate-infra-outcome R2): at least
#      one phase could not run at all (reviewer-agent's `claude -p` failed
#      under quota, a producer's binary was missing, a crash rc>=2 — see
#      note_infra call sites) and no OTHER receipt blocked — distinct from
#      both 0 (pass) and 1 (block): this is "the harness could not tell",
#      never "the code is broken". The journal line reads `gate <target>
#      incomplete (… infra=<phase>[,<phase>] …)`; the caller (gate-then-
#      land.sh) retries rather than treating this as a red gate.
#
# --record-baseline: runs the full producer sequence exactly as a normal
# invocation, then instead of computing a delta verdict, writes
# `<build_into>/agent/gate-baseline.json` from THIS run's blocking receipt
# set (`scripts/gate-delta.sh record`) and prints the recorded document.
# Meant to be committed by the caller (a human, or an explicit gate-debt
# PRD) — this script never commits, and a plain verdict run never widens
# or auto-records a baseline on its own. Bypasses the verdict cache below
# (a recording always reflects a fresh run). Exits 0 on a successful
# write regardless of the underlying pass/block count.
#
# Verdict cache: on a successful (non-dry-run, non-record-baseline) run,
# the computed verdict is cached at
# `<project>/target/autobuilder/last-verdict.json` keyed on (HEAD sha,
# this script's own sha256). A later invocation at the SAME head with an
# UNCHANGED script replays the cached verdict (`extend-gate: verdict=...
# (cached)`, same exit code) instead of regenerating all 25 receipts.
# `--force` bypasses the cache and always runs the full sequence.
#
# Never runs `cargo clean` in the crate's own target/ (determinism and
# cold-build-time already build in their own temp target dirs — memory
# rule: never `cargo clean` a crate with receipts).
#
# Takes the SAME per-repo integration lock `worktree-extend.sh integrate`
# takes (`<repo>/.git/autobuilder-integrate.lock`, `flock`), held from
# BEFORE the first producer runs (scripts/audit.sh) through the final
# `autobuilder gate` accounting step, so two PRDs landing on one crate in
# one tick — or N concurrent gate invocations dispatched against one
# shared build_into in the same tick, PRD-build-extend-gate-concurrent-
# isolation — never run producers concurrently: the second (and every
# subsequent) run waits for the lock, then regenerates receipts at the
# HEAD it sees once it acquires it (the later HEAD, if one landed in the
# meantime). A run that cannot acquire the lock within
# $EXTEND_GATE_PRODUCER_LOCK_WAIT seconds (default 90) fails closed — see
# exit code 4 below — rather than ever reading a receipt set another
# invocation may still be mid-write on.
#
# --dry-run prints the producer sequence, the resolved base tag, and HEAD;
# writes nothing under target/autobuilder/; never takes the lock; exits 0.
#
# Individual producer steps are run best-effort: a non-zero exit from any
# one of them (rollback-plan finding a non-revert-clean merge, ci-checks
# finding a red workflow, ...) is logged and the run CONTINUES through the
# rest of the sequence, so every receipt gets regenerated at HEAD and the
# final `autobuilder gate` is the single source of truth for pass/block —
# an early abort would leave the receipt set partial and mislead the next
# tick about which check actually failed. Per requirement 7 (resumable): a
# tick that ends mid-gate leaves a partial receipt set, which is never
# read as green; the next tick reruns this script from the start.
set -uo pipefail
BUILD_SCRIPTS="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=lib/probe.sh
source "$BUILD_SCRIPTS/lib/probe.sh"
# shellcheck source=lib/journal.sh
source "$BUILD_SCRIPTS/lib/journal.sh"
# shellcheck source=lib/repo-slug.sh
source "$BUILD_SCRIPTS/lib/repo-slug.sh"
# PRD-build-flow-ledger requirement 2: this script is the sole writer of
# the ledger's `gate_verdict` event, appended once the outcome is final
# (right after this run's own journal line, below) — never re-derived
# later from a journal grep. Skipped when $slug is empty (a bare
# --scope main run with neither --pinned-landing nor --main-health has no
# PRD to attribute the verdict to, same condition scope_prefix above
# already uses).
# shellcheck source=lib/flow-ledger.sh
source "$BUILD_SCRIPTS/lib/flow-ledger.sh"
# shellcheck source=lib/gate-patience.sh
# PRD-build-gate-patience-from-queue-depth requirement 1: derives how long
# the producer-lock wait below should be from the ACTUAL queue in front of
# this gate, instead of the fixed EXTEND_GATE_PRODUCER_LOCK_WAIT constant
# alone (that constant becomes the FLOOR, not the whole answer — see the
# lib's own header).
source "$BUILD_SCRIPTS/lib/gate-patience.sh"
# shellcheck source=lib/push-via-branch.sh
STATE_DIR="${BUILD_STATE_DIR:-$BUILD_SCRIPTS/../state}"
source "$BUILD_SCRIPTS/lib/push-via-branch.sh"

# --- PATH order guard (P0 requirement 1, PRD-build-gate-cargo-route-attest;
#     rewritten under PRD-build-cargo-route-precedence) -------------------
# Previously this unconditionally prepended the real cargo/local-bin dirs
# ahead of whatever $PATH the caller armed, silently shadowing the
# burst-lane shim (scripts/burst-lane-bin/cargo) even when a caller had
# already exported it first per SKILL.md's "mixed-tick burst routing"
# section — the root cause of 53 autobuilder loops + 34 gate `cargo test`
# runs all landing on RedBaron on 2026-09-10 while casper sat idle at 3%
# utilization for EUR9.59. That fix then regressed the SAME way on
# 2026-09-15: the guard only self-armed under the legacy per-invocation
# `BURST_LANE=1` flag, which had drifted from whether a burst box was
# actually configured, so a gate ran `cargo test` locally while a real box
# was up (166 route=local vs 49 route=burst that day). Now: this guard
# ALWAYS arms scripts/lib/cargo-route.sh's own cargo_route_export_path()
# (single source of truth, shared with run_unslotted_producer() below and
# with burst-lane.sh's own route-check), which prepends cargo-budget-bin
# (always) and burst-lane-bin (only when burst_configured — never the
# legacy flag alone) — idempotent, so a caller that already exported the
# same prefix ahead of everything else keeps it exactly where it was.
# $HOME/.cargo/bin and $HOME/.local/bin stay APPENDED (never prepended),
# so nothing this guard adds, or the caller already armed, is ever
# shadowed by them. The resolved cargo path is logged once, right here,
# before any producer — before even repo validation — runs.
CARGO_ROUTE_LIB="$BUILD_SCRIPTS/lib/cargo-route.sh"
if [ -r "$CARGO_ROUTE_LIB" ]; then
  # shellcheck source=lib/cargo-route.sh
  source "$CARGO_ROUTE_LIB"
  cargo_route_export_path
else
  # Fails open (never blocks the gate) if the lib is missing — same
  # convention as every other sourced helper in this script — but the
  # route is then whatever the caller's own $PATH already resolves.
  :
fi
export PATH="$PATH:$HOME/.cargo/bin:$HOME/.local/bin"
_extend_gate_resolved_cargo="$(command -v cargo 2>/dev/null || true)"
# PRD-build-branch-gate-scope-artifacts requirement 5/AC7 (found live):
# stderr, not stdout — this is a human-facing diagnostic ("logged once,
# right here", not part of any mode's return value), but it ran BEFORE
# --print-verdict-path's/--phases-json's early exits, which promise a
# single clean stdout value for a caller to consume programmatically.
# On stdout it silently became a SECOND line gate-then-land.sh's own
# `verdict_path="$(... --print-verdict-path)"` capture never expected,
# so `[ -f "$verdict_path" ]` always failed and every real land hit
# `land-ungated (verdict=missing)` even on a genuine pass — caught by
# bgscope_ac7_land_reruns_deferred_at_main_scope.sh running gate-then-
# land.sh for real (a prior hand-rolled fake-extend-gate harness never
# exercised this real interaction).
echo "extend-gate: cargo=${_extend_gate_resolved_cargo:-not-found}" >&2

