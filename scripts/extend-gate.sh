# 5. rollback-plan over <base>..HEAD.
# PRD-build-branch-gate-scope-artifacts requirement 1 (P0, AC1): at
# `--scope branch`, a `head-untagged` block is a scope artifact — no
# branch HEAD ever carries a release tag, only main does, after a ship
# (Problem statement: 14/14 branch gates on 2026-09-15 blocked here alone).
# autobuilder's rollback.rs itself is untouched (Non-goals: the policy
# lives in the caller); this script post-classifies the receipt IT wrote:
# when `block_reason == head-untagged` and the receipt's own `head_sha`
# matches this run's actual HEAD (i.e. it is a fresh receipt for exactly
# this commit, not a stale leftover — the freshness guard the PRD's
# fallback text names as "commit_count == <branch commit count>"; a raw
# git commit count does not correspond to rollback.rs's own commit_count
# field, which counts version-bump commits, not all commits, so head_sha
# freshness is the meaningful, robust form of that same check), the block
# is rewritten to a pass ON DISK — `autobuilder gate` below reads receipts
# fresh off disk and has no other notion of "deferred", so this is what
# keeps its aggregate from blocking on a scope artifact — and recorded
# `scope-deferred` here. `land` re-runs this producer at `--scope main`
# before tagging (requirement 5), where a real tag is expected and this
# deferral path is never reached (scope != branch).
_phase_t0=$(date +%s)
rollback_receipt="$project_abs/target/autobuilder/receipts/rollback-plan.json"
if ( cd "$repo" && autobuilder rollback-plan --project "$project_rel" --base "$base_ref" ) 9>&-; then
  record_phase rollback-plan $(( $(date +%s) - _phase_t0 )) ok
else
  rollback_deferred=false
  if [ "$scope" = branch ] && [ -f "$rollback_receipt" ]; then
    _rb_reason="$(jq -r '.block_reason // empty' "$rollback_receipt" 2>/dev/null)"
    _rb_head="$(jq -r '.head_sha // empty' "$rollback_receipt" 2>/dev/null)"
    if [ "$_rb_reason" = "head-untagged" ] && [ -n "$_rb_head" ] && [ "$_rb_head" = "$head_now" ]; then
      rollback_deferred=true
    fi
  fi
  if $rollback_deferred; then
    _tmp_rb="$(mktemp "${TMPDIR:-/tmp}/extend-gate-rollback-defer.XXXXXX")"
    if jq '.verdict = "pass" | .scope_deferred = true' "$rollback_receipt" > "$_tmp_rb" 2>/dev/null; then
      mv "$_tmp_rb" "$rollback_receipt"
    else
      rm -f "$_tmp_rb" 2>/dev/null || true
    fi
    note_defer "rollback-plan — scope-deferred (head-untagged) — branch HEAD carries no release tag; land re-runs this at main scope"
    record_phase rollback-plan $(( $(date +%s) - _phase_t0 )) defer
  else
    note_block "rollback-plan — commits since $base_ref are not all revert-clean (see target/autobuilder/rollback.md); fix forward, or a human rewrites history and says so — this script never edits history to force a pass"
    record_phase rollback-plan $(( $(date +%s) - _phase_t0 )) fail
  fi
fi

# 6. reviewer-agent: prepare, spawn the independent review headlessly via
#    `claude -p --model sonnet` (same tier /rustbuild routes it to; the
#    autobuilder binary cannot spawn a Claude subagent itself), finalize.
#
# PRD-build-reviewer-receipt-primary: the subagent's own prompt (R7) says
# receipts/reviewer-agent.json IS the deliverable — this function reads
# that file as the phase's PRIMARY input (R1) and only falls back to
# balanced-decoding the subagent's raw stdout (R2, reviewer-receipt-
# resolve.py, replacing the old greedy `\{.*\}` regex this superseded)
# when no fresh receipt exists. "Fresh" means: right schema, head_sha
# matches THIS gate's head, and reviewed_at (or mtime) is at or after this
# run's own `prepare` call — never a stale receipt left by a previous gate
# on the same or a different head (05:15:46Z misdiagnosis, Grounding).
#
# PRD-build-gate-route-parity-ledger requirement 4 (R4/AC4) still holds:
# a mechanism failure (prepare/claude/prompt/invocation all failing before
# a verdict is ever reached) is never reported as `decision=block` — it
# sets $_reviewer_verdict=infra, never `block`, so a 25/25-pass gate line
# never again carries a false "reviewer-agent — ..." block line
# (09-15 22:48:50Z). $_reviewer_verdict is one of: ok | block | infra —
# the call site below decides note_block/record_phase purely off this
# flag, never by re-reading reviewer-agent.json itself (that re-read is
# exactly the bug this PRD fixes: it could not tell a fresh verdict from a
# stale leftover).
# PRD-build-gate-infra-outcome R8: last 20 lines of the failing command's
# stderr (when one was captured) plus its exit code, set alongside
# _reviewer_verdict="infra" at every early-exit below. Not every infra
# branch has a subprocess to attribute (a plain `[ -f ... ]` test has no
# stderr) — those set a bare "rc=<n>" or leave it empty rather than
# fabricate detail that was never captured.
# PRD-build-gate-infra-outcome AC12 (2026-09-17 amendment, proof-lane
# 15:54:42Z regression): `finalize` can reject a reviewer object that DID
# carry a real decision (a sha-prefix mismatch on an otherwise-valid block
# verdict) — treating that purely as generic infra would make a genuine
# finding invisible. `_reviewer_infra_kind` distinguishes this one infra
# sub-case ("finalize-rejected") from every other early-return above (all
# of which leave it empty); `_reviewer_rejected_verdict` carries the
# rejected object's own decision/block_reasons through to the written
# receipt (see the `infra)` call site) even though the RUN's own verdict
# stays `infra`, never `block` — R4's rule (a mechanism failure is never
# reported as a verdict) is unchanged, this only keeps the finding legible.
_reviewer_fail_note=""
_reviewer_infra_detail=""
_reviewer_infra_kind=""
_reviewer_rejected_verdict='{}'
_reviewer_verdict="ok"          # ok | block | infra
_reviewer_block_reasons_csv=""
run_reviewer() {
  _reviewer_fail_note=""
  _reviewer_infra_detail=""
  _reviewer_infra_kind=""
  _reviewer_rejected_verdict='{}'
  _reviewer_verdict="ok"
  _reviewer_block_reasons_csv=""
  ( cd "$repo" && autobuilder reviewer-agent prepare --project "$project_rel" --base "$base_ref" ) 9>&- \
    || { local _rp_rc=$?; _reviewer_fail_note="reviewer-agent — prepare exited non-zero"; _reviewer_infra_detail="rc=$_rp_rc"; _reviewer_verdict="infra"; return 1; }
  local req="$project_abs/target/autobuilder/review-request.json"
  [ -f "$req" ] || { _reviewer_fail_note="reviewer-agent — prepare did not write $req"; _reviewer_verdict="infra"; return 1; }
  local prepare_epoch
  prepare_epoch="$(stat -c %Y "$req" 2>/dev/null || stat -f %m "$req" 2>/dev/null || date +%s)"
  command -v claude >/dev/null 2>&1 \
    || { _reviewer_fail_note="reviewer-agent — claude CLI not on \$PATH (needed to spawn the independent review subagent)"; _reviewer_verdict="infra"; return 1; }
  [ -f "$REVIEWER_PROMPT" ] \
    || { _reviewer_fail_note="reviewer-agent — missing prompt $REVIEWER_PROMPT"; _reviewer_verdict="infra"; return 1; }

  local out="$project_abs/target/autobuilder/review-output.json"
  local raw="$project_abs/target/autobuilder/review-output.raw.txt"
  local receipt="$project_abs/target/autobuilder/receipts/reviewer-agent.json"
  local prompt
  prompt="$(cat "$REVIEWER_PROMPT")
---
Below is this review's target/autobuilder/review-request.json. The repo is
checked out at HEAD $head_now at $repo — read whatever you need under it.
$(cat "$req")
---
Reply with ONLY one JSON object, no prose, no markdown fences, matching
schema autobuilder.reviewer_agent_receipt.v1. intent_card_sha is copied
verbatim from review-request.json's intent_card_sha256 (prefix included) —
do not recompute it yourself:
{\"schema\":\"autobuilder.reviewer_agent_receipt.v1\",\"head_sha\":\"...\",\"intent_card_sha\":\"<copy intent_card_sha256 from review-request.json verbatim>\",\"decision\":\"pass|concern|block\",\"block_reasons\":[...],\"concern_reasons\":[{\"id\":\"...\",\"note\":\"...\"}],\"falsification\":{\"test_audit\":\"...\",\"panic_audit\":\"...\",\"unsafe_audit\":\"...\",\"public_api_audit\":\"...\",\"deps_audit\":\"...\",\"drift_audit\":\"...\",\"counter_attack\":{\"description\":\"...\",\"test_skeleton\":\"...\"}}}"

  if ! ( cd "$repo" && claude -p "$prompt" --model sonnet --permission-mode bypassPermissions --output-format text ) 9>&- >"$raw" 2>"$raw.err"; then
    local _cp_rc=$?
    _reviewer_fail_note="reviewer-agent — claude -p subagent invocation failed (see $raw.err)"
    # R8: the 2026-09-17 failures had an EMPTY .err file, so the cause was
    # unknown after the fact — this captures whatever is there (rc always,
    # stderr tail when non-empty) so the next such failure is diagnosable
    # from the receipt alone, no worktree required.
    _reviewer_infra_detail="rc=$_cp_rc"
    if [ -s "$raw.err" ]; then
      _reviewer_infra_detail="$_reviewer_infra_detail stderr_tail=$(tail -n 20 "$raw.err" | tr '\n' ' ' | cut -c1-2000)"
    else
      _reviewer_infra_detail="$_reviewer_infra_detail stderr_tail=<empty>"
    fi
    _reviewer_verdict="infra"
    return 1
  fi

  local resolve_json
  resolve_json="$(python3 "$BUILD_SCRIPTS/reviewer-receipt-resolve.py" "$receipt" "$raw" "$head_now" "$prepare_epoch" 2>>"$raw.err")"
  [ -n "$resolve_json" ] || resolve_json='{}'

  local fresh
  fresh="$(printf '%s' "$resolve_json" | jq -r '.fresh // false' 2>/dev/null)"

  if [ "$fresh" = "true" ]; then
    # R1: the subagent's own receipt is the phase's input — stdout is not
    # parsed for the verdict, only compared against it for R3 below.
    # AC12: receipt_decision/reasons are read BEFORE calling finalize (not
    # after, as before this amendment) so a finalize rejection still has
    # the object's own verdict on hand to carry into rejected_verdict.
    local receipt_decision receipt_reasons_csv
    receipt_decision="$(printf '%s' "$resolve_json" | jq -r '.receipt_decision // empty')"
    receipt_reasons_csv="$(printf '%s' "$resolve_json" | jq -r '(.receipt_reasons // []) | join(",")')"
    local _finalize_err
    _finalize_err="$(mktemp "${TMPDIR:-/tmp}/extend-gate-finalize-err.XXXXXX")"
    if ! ( cd "$repo" && autobuilder reviewer-agent finalize --project "$project_rel" --input "$receipt" ) 9>&- 2>"$_finalize_err"; then
      _reviewer_fail_note="reviewer-agent — finalize rejected the subagent's receipt"
      _reviewer_infra_kind="finalize-rejected"
      _reviewer_infra_detail="$(tail -n 20 "$_finalize_err" | tr '\n' ' ' | cut -c1-2000)"
      _reviewer_rejected_verdict="$(jq -n --arg d "$receipt_decision" --arg r "$receipt_reasons_csv" \
        '{decision: $d, block_reasons: ($r | if . == "" then [] else split(",") end)}')"
      rm -f "$_finalize_err"
      _reviewer_verdict="infra"
      return 1
    fi
    rm -f "$_finalize_err"
    local stdout_found stdout_decision
    stdout_found="$(printf '%s' "$resolve_json" | jq -r '.stdout_object_found // false')"
    if [ "$stdout_found" = "true" ]; then
      stdout_decision="$(printf '%s' "$resolve_json" | jq -r '.stdout_decision // empty')"
      # R3: receipt file wins on any disagreement; one journal line notes it.
      if [ -n "$stdout_decision" ] && [ "$stdout_decision" != "$receipt_decision" ]; then
        journal_line --file "$journal" "$(date -u +%FT%TZ)  gate  ${repo##*/}  reviewer-receipt-vs-stdout mismatch file=${receipt_decision} stdout=${stdout_decision} head=${head_now:0:7}"
      fi
    fi
    if [ "$receipt_decision" = "block" ]; then
      _reviewer_block_reasons_csv="$receipt_reasons_csv"
      _reviewer_fail_note="reviewer-agent — decision=block reasons=${_reviewer_block_reasons_csv}"
      _reviewer_verdict="block"
      return 1
    fi
    _reviewer_verdict="ok"
    return 0
  fi

  # No fresh receipt — R2 fallback: balanced-decode the raw stdout (never
  # the greedy `\{.*\}` regex, which a background-agent notification's own
  # prose braces can defeat, AC4).
  local stdout_found
  stdout_found="$(printf '%s' "$resolve_json" | jq -r '.stdout_object_found // false')"
  if [ "$stdout_found" = "true" ]; then
    printf '%s' "$resolve_json" | jq -c '._stdout_object' > "$out"
    # AC12: same as the receipt path above — read the object's own
    # decision/reasons before finalize can reject it.
    local stdout_decision stdout_reasons_csv
    stdout_decision="$(printf '%s' "$resolve_json" | jq -r '.stdout_decision // empty')"
    stdout_reasons_csv="$(printf '%s' "$resolve_json" | jq -r '(.stdout_reasons // []) | join(",")')"
    local _finalize_err2
    _finalize_err2="$(mktemp "${TMPDIR:-/tmp}/extend-gate-finalize-err.XXXXXX")"
    if ! ( cd "$repo" && autobuilder reviewer-agent finalize --project "$project_rel" --input "$out" ) 9>&- 2>"$_finalize_err2"; then
      _reviewer_fail_note="reviewer-agent — finalize rejected the subagent's output"
      _reviewer_infra_kind="finalize-rejected"
      _reviewer_infra_detail="$(tail -n 20 "$_finalize_err2" | tr '\n' ' ' | cut -c1-2000)"
      _reviewer_rejected_verdict="$(jq -n --arg d "$stdout_decision" --arg r "$stdout_reasons_csv" \
        '{decision: $d, block_reasons: ($r | if . == "" then [] else split(",") end)}')"
      rm -f "$_finalize_err2"
      _reviewer_verdict="infra"
      return 1
    fi
    rm -f "$_finalize_err2"
    if [ "$stdout_decision" = "block" ]; then
      _reviewer_block_reasons_csv="$stdout_reasons_csv"
      _reviewer_fail_note="reviewer-agent — decision=block reasons=${_reviewer_block_reasons_csv}"
      _reviewer_verdict="block"
      return 1
    fi
    _reviewer_verdict="ok"
    return 0
  fi

  # R4: neither a fresh receipt nor a parseable stdout object — an infra
  # failure, distinct from a verdict, and never `decision=block`.
  local found_head found_head7 found_reviewed_at
  found_head="$(printf '%s' "$resolve_json" | jq -r '.receipt_head // empty')"
  found_head7="${found_head:0:7}"
  [ -z "$found_head7" ] && found_head7="none"
  found_reviewed_at="$(printf '%s' "$resolve_json" | jq -r '.receipt_reviewed_at // empty')"
  [ -z "$found_reviewed_at" ] && found_reviewed_at="none"
  _reviewer_fail_note="reviewer-agent — no fresh receipt (found head=${found_head7} reviewed_at=${found_reviewed_at})"
  _reviewer_verdict="infra"
  return 1
}

# 7. ci-checks — needs `gh` authenticated against the pushed HEAD.
ci_checks_receipt="$project_abs/target/autobuilder/receipts/ci-checks.json"
if ! command -v gh >/dev/null 2>&1; then
  note_block "ci-checks — gh CLI not on \$PATH (install: https://cli.github.com)"
  record_phase ci-checks 0 skip
elif ! gh auth status >/dev/null 2>&1; then
  note_block "ci-checks — gh not authenticated: run 'gh auth login'"
  record_phase ci-checks 0 skip
elif [ "$scope" = branch ]; then
  # PRD-build-branch-gate-scope-artifacts requirement 2 (P0, AC2/AC3): a
  # branch gate runs BEFORE land — main scope's assumption (CI has already
  # run by the time a gate checks it) never holds here, so `run_count==0`
  # is a scope artifact, not a real defect (Problem statement: `ci-checks`
  # blocked with `run_count: 0` on every one of 14 branch gates because the
  # branch was never pushed). `BRANCH_GATE_PUSH` (default 1) controls
  # whether THIS gate pushes the branch itself under its own name (the
  # worktree's branch, created by worktree-extend.sh add, is already named
  # `autobuilder/<slug>` — falls back to that literal name if HEAD is
  # somehow detached) before asking `ci-checks` to look for runs, polling
  # up to `CI_CHECKS_BRANCH_WAIT` seconds (default 900) for one to appear.
  # `autobuilder gate` below reads every receipt straight off disk and
  # counts a MISSING file as a hard fail (unlike a present receipt whose
  # verdict this script can rewrite) — a deferral that never invokes
  # `autobuilder ci-checks` at all (push-disabled, push-failed), or whose
  # one call errors before it ever gets to write a receipt (e.g. `origin`
  # resolves but isn't a github.com URL — the exact shape of the fixture
  # requirement 6 adds: a bare local `origin`, per ci_checks.rs's
  # `try_detect_repo`, which errors rather than skips on an unparseable
  # remote), must synthesize a minimal digest-bound receipt itself so the
  # gate has something to read as passing. write_ci_defer_receipt does
  # that; the in-place jq rewrite below stays for the one case where a
  # real receipt WAS written (run_count==0, clean block).
  write_ci_defer_receipt() {  # $1=skip_reason
    jq -n --arg head "$head_now" --arg reason "$1" '{
      schema: "autobuilder.ci_checks_receipt.v1",
      head_sha: $head, repo: "", run_count: 0, success_count: 0,
      failure_count: 0, pending_count: 0, runs: [],
      verdict: "pass", scope_deferred: true, skip_reason: $reason,
      captured_at: (now | todateiso8601), receipt_digest: ""
    }' > "$ci_checks_receipt" 2>/dev/null
  }
  _phase_t0=$(date +%s)
  if [ "${BRANCH_GATE_PUSH:-1}" = "0" ]; then
    write_ci_defer_receipt "push-disabled: BRANCH_GATE_PUSH=0, branch was never pushed"
    note_defer "ci-checks — scope-deferred (push-disabled) — BRANCH_GATE_PUSH=0, branch was never pushed; land re-runs this at main scope"
    record_phase ci-checks 0 defer
  else
    _push_ref="$(git -C "$repo" symbolic-ref --short HEAD 2>/dev/null || echo "autobuilder/$slug")"
    if ! ( cd "$repo" && git push origin "HEAD:refs/heads/$_push_ref" ) >&2; then
      write_ci_defer_receipt "push-failed: could not push $_push_ref to origin"
      note_defer "ci-checks — scope-deferred (push-failed) — could not push $_push_ref to origin; land re-runs this at main scope"
      record_phase ci-checks 0 defer
    else
      _ci_wait_s="${CI_CHECKS_BRANCH_WAIT:-900}"
      _ci_poll_s="${CI_CHECKS_BRANCH_POLL:-15}"
      _ci_deadline=$(( $(date +%s) + _ci_wait_s ))
      _ci_ok=false
      while :; do
        if ( cd "$repo" && autobuilder ci-checks --project "$project_rel" ) 9>&-; then
          _ci_ok=true
          break
        fi
        # A receipt with runs already on it (pending/failed, not just
        # absent) is real CI signal, not a scope artifact — stop polling
        # and let it fall through to the normal block below instead of
        # waiting out the full deadline for nothing. A receipt that was
        # never written at all (ci-checks errored before writing one —
        # e.g. an unparseable origin URL) reads as 0 the same way, via the
        # `|| echo 0` fallback below, and keeps polling/deferring exactly
        # like a written run_count==0 receipt would.
        _ci_run_count="$(jq -r '.run_count // 0' "$ci_checks_receipt" 2>/dev/null || echo 0)"
        [ "$_ci_run_count" != "0" ] && break
        [ "$(date +%s)" -ge "$_ci_deadline" ] && break
        sleep "$_ci_poll_s"
      done
      if $_ci_ok; then
        record_phase ci-checks $(( $(date +%s) - _phase_t0 )) ok
      else
        _ci_run_count="$(jq -r '.run_count // 0' "$ci_checks_receipt" 2>/dev/null || echo 0)"
        if [ "$_ci_run_count" = "0" ]; then
          if [ -f "$ci_checks_receipt" ] && jq -e . "$ci_checks_receipt" >/dev/null 2>&1; then
            _tmp_ci="$(mktemp "${TMPDIR:-/tmp}/extend-gate-ci-defer.XXXXXX")"
            if jq '.verdict = "pass" | .scope_deferred = true' "$ci_checks_receipt" > "$_tmp_ci" 2>/dev/null; then
              mv "$_tmp_ci" "$ci_checks_receipt"
            else
              rm -f "$_tmp_ci" 2>/dev/null || true
            fi
          else
            write_ci_defer_receipt "no-runs-on-ref: ci-checks never wrote a receipt within ${_ci_wait_s}s (see gate output above)"
          fi
          note_defer "ci-checks — scope-deferred (no-runs-on-ref) — no workflow runs observed for $head_now within ${_ci_wait_s}s; land re-runs this at main scope"
          record_phase ci-checks $(( $(date +%s) - _phase_t0 )) defer
        else
          note_block "ci-checks — workflow(s) on HEAD are not green, or still pending (the next tick retries)"
          record_phase ci-checks $(( $(date +%s) - _phase_t0 )) fail
        fi
      fi
    fi
  fi
else
  _phase_t0=$(date +%s)
  _repo_slug_for_ci="$(basename "$repo")"
  # PRD-build-main-verdict-pinned-to-landing R6/AC8: main-health always
  # takes the direct "runs at HEAD" branch below, even on a
  # push_via_branch=true repo — there is no slug/PR to key a
  # `branch-protection.sh pr-checks` lookup on (that call needs a real
  # landed PRD slug), and R6's own wording is explicit: "ci-checks from
  # Actions runs at HEAD". A pinned-landing call (which DOES have a real
  # slug/PR) is unaffected — this only widens the condition below with an
  # extra `! $main_health` guard, never removes the existing branch.
  if ! $main_health && [ "$(push_via_branch_for "$_repo_slug_for_ci")" = "true" ]; then
    # PRD-build-main-push-gate-pr-path requirement 4 (P0, AC6): a
    # push_via_branch=true repo's main-scope `ci-checks` can never be
    # "runs at HEAD" — HEAD here is a local, unpushed commit on a repo
    # whose main refuses a direct push (GH006); the only CI signal that
    # will ever exist for this land is the PR's OWN required checks,
    # captured via the landing record `branch-protection.sh push` wrote
    # and read back here through `branch-protection.sh pr-checks` (one
    # `gh` call, no push of `main`, no polling wait — this producer either
    # has an answer already or it does not).
    _ci_slug_for_ci="${slug:-$_repo_slug_for_ci}"
    if _ci_pr_checks_json="$("$BUILD_SCRIPTS/branch-protection.sh" pr-checks "$repo" "$_ci_slug_for_ci" 2>/dev/null)"; then
      jq -n --arg head "$head_now" --argjson pr "$_ci_pr_checks_json" '
        ($pr.contexts // []) as $ctx |
        {
          schema: "autobuilder.ci_checks_receipt.v1",
          head_sha: ($pr.merge_sha // "" | if . == "" then $head else . end),
          repo: "", pr_number: $pr.pr_number, pr_state: $pr.state,
          run_count: ($ctx | length),
          success_count: ($ctx | map(select(.conclusion == "SUCCESS")) | length),
          failure_count: ($ctx | map(select(.conclusion == "FAILURE")) | length),
          pending_count: ($ctx | map(select(.conclusion == "PENDING")) | length),
          runs: $ctx,
          verdict: (if ($pr.state == "MERGED") and (($pr.merge_sha // "") != "")
                       and (($ctx | length) > 0)
                       and (($ctx | map(select(.conclusion != "SUCCESS")) | length) == 0)
                    then "pass" else "block" end),
          scope_deferred: false,
          skip_reason: (if ($pr.state == "MERGED") and (($pr.merge_sha // "") != "")
                           and (($ctx | length) > 0)
                           and (($ctx | map(select(.conclusion != "SUCCESS")) | length) == 0)
                        then "" else "pr-checks-not-green" end),
          captured_at: (now | todateiso8601), receipt_digest: ""
        }' > "$ci_checks_receipt" 2>/dev/null
      if [ "$(jq -r '.verdict' "$ci_checks_receipt" 2>/dev/null)" = "pass" ]; then
        record_phase ci-checks $(( $(date +%s) - _phase_t0 )) ok
      else
        note_block "ci-checks — push_via_branch=true, PR#$(jq -r '.pr_number' "$ci_checks_receipt" 2>/dev/null) required checks are not all SUCCESS yet (state=$(jq -r '.pr_state' "$ci_checks_receipt" 2>/dev/null); the next tick's landing-check/sync retries)"
        record_phase ci-checks $(( $(date +%s) - _phase_t0 )) fail
      fi
    else
      jq -n --arg head "$head_now" '{
        schema: "autobuilder.ci_checks_receipt.v1",
        head_sha: $head, repo: "", run_count: 0, success_count: 0,
        failure_count: 0, pending_count: 0, runs: [],
        verdict: "block", scope_deferred: false, skip_reason: "no-landing-record",
        captured_at: (now | todateiso8601), receipt_digest: ""
      }' > "$ci_checks_receipt" 2>/dev/null
      note_block "ci-checks — push_via_branch=true, no landing record for $_repo_slug_for_ci (branch-protection.sh push never ran, or it was already consumed) — verdict=block, skip_reason=no-landing-record"
      record_phase ci-checks $(( $(date +%s) - _phase_t0 )) fail
    fi
  elif ( cd "$repo" && autobuilder ci-checks --project "$project_rel" ) 9>&-; then
    record_phase ci-checks $(( $(date +%s) - _phase_t0 )) ok
  else
    note_block "ci-checks — workflow(s) on HEAD are not green, or still pending (the next tick retries)"
    record_phase ci-checks $(( $(date +%s) - _phase_t0 )) fail
  fi
fi

