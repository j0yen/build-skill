# --- cargo project root resolution (PRD-build-extend-gate-nested-crate-project) ---
# $repo itself wins immediately if it has a Cargo.toml (the common case,
# and the edge case of a repo with both a root AND a nested Cargo.toml —
# root wins, no search performed at all, so byte-identical behavior for
# every already-onboarded crate). Otherwise search one level down, then
# two, for exactly one Cargo.toml, skipping target/ and .git/ at every
# level. Prints the resolved path on success; prints a human-readable
# reason (ambiguous / absent, naming what was searched) on failure.
find_cargo_root() {
  local base="$1"
  if [ -f "$base/Cargo.toml" ]; then
    printf '%s\n' "$base"
    return 0
  fi
  local d b
  local -a d1=()
  for d in "$base"/*/; do
    [ -d "$d" ] || continue
    b="$(basename "$d")"
    case "$b" in target|.git) continue ;; esac
    [ -f "$d/Cargo.toml" ] && d1+=("${d%/}")
  done
  if [ "${#d1[@]}" -eq 1 ]; then
    printf '%s\n' "${d1[0]}"
    return 0
  elif [ "${#d1[@]}" -gt 1 ]; then
    # Disambiguate the common <repo>/<repo>/Cargo.toml nesting pattern: if
    # exactly one candidate's basename matches the repo's own basename,
    # prefer it over unrelated sibling dirs (e.g. a "tools/" cargo
    # workspace). Only fires inside this already-ambiguous branch, so
    # repos without this exact collision are unaffected.
    local base_name="$(basename "$base")" self_match="" self_count=0 cand
    for cand in "${d1[@]}"; do
      if [ "$(basename "$cand")" = "$base_name" ]; then
        self_match="$cand"
        self_count=$((self_count + 1))
      fi
    done
    if [ "$self_count" -eq 1 ]; then
      printf '%s\n' "$self_match"
      return 0
    fi
    printf 'ambiguous — multiple Cargo.toml found one level under %s: %s' "$base" "${d1[*]}"
    return 1
  fi
  local d1dir b1 d2dir b2
  local -a d2=()
  for d1dir in "$base"/*/; do
    [ -d "$d1dir" ] || continue
    b1="$(basename "$d1dir")"
    case "$b1" in target|.git) continue ;; esac
    for d2dir in "$d1dir"*/; do
      [ -d "$d2dir" ] || continue
      b2="$(basename "$d2dir")"
      case "$b2" in target|.git) continue ;; esac
      [ -f "$d2dir/Cargo.toml" ] && d2+=("${d2dir%/}")
    done
  done
  if [ "${#d2[@]}" -eq 1 ]; then
    printf '%s\n' "${d2[0]}"
    return 0
  elif [ "${#d2[@]}" -gt 1 ]; then
    # Same repo-basename tie-break as the one-level-down case, mirrored
    # for consistency (untested pattern — the one-level case above is the
    # one actually observed).
    local base_name2="$(basename "$base")" self_match2="" self_count2=0 cand2
    for cand2 in "${d2[@]}"; do
      if [ "$(basename "$cand2")" = "$base_name2" ]; then
        self_match2="$cand2"
        self_count2=$((self_count2 + 1))
      fi
    done
    if [ "$self_count2" -eq 1 ]; then
      printf '%s\n' "$self_match2"
      return 0
    fi
    printf 'ambiguous — multiple Cargo.toml found two levels under %s: %s' "$base" "${d2[*]}"
    return 1
  fi
  printf 'no Cargo.toml found at %s, in its immediate subdirectories, or two levels down (searched depth-1 and depth-2, excluding target/ and .git/)' "$base"
  return 1
}

