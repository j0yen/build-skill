# 9. the risk gate itself — authoritative pass/block, reads all 25 receipts.
# Quota guard (Joe 2026-09-11): the reviewer is a Sonnet `claude -p` call. It runs LAST, and only
# when every other producer passed — a red gate never pays for a review it cannot use. The next gate
# on a fixed HEAD runs it. On 2026-09-11 five reviewer runs shipped nothing.
#
# PRD-build-branch-gate-scope-artifacts requirement 3 (P0, AC4/AC6): at
# `--scope branch` the quota guard above does not apply — a branch gate is
# a one-shot evaluation (not main's repeated-retry loop the guard was
# built for), and the whole point of this PRD is that the reviewer's
# finding is attached whether the branch passes OR blocks (user story:
# "when my branch is wrong, I want ... the reviewer's finding, so the next
# step fixes the cause"; AC6: a branch with a failing test still gets a
# reviewer-agent receipt alongside its in-scope block). `--scope main`
# keeps the pre-existing skip-on-any-block behavior unchanged (Non-goals:
# main-scope semantics untouched).
#
# PRD-build-intent-card-pregate-refresh R4 (P0, AC3/AC4): the one
# exception to "branch scope always runs the reviewer regardless of other
# blocks" above — a STALE card (intent_card_stale, set by the pre-gate
# refresh step above) means there is nothing true for the reviewer to
# compare the diff against, so its finding would be noise, not signal.
# `intent_card_stale` is always false at `--scope main` (the refresh step
# only runs at branch scope), so main-scope semantics are unaffected; at
# branch scope with a stale card, blocking_notes already carries the
# `intent-card-stale` note from that step, so the second disjunct is also
# false and reviewer-agent is skipped via the same "skipped" branch below.
_phase_t0=$(date +%s)
if $main_health; then
  # PRD-build-main-verdict-pinned-to-landing R6/AC8: a bare-HEAD
  # main-health gate never has a PRD/slug to review a range against (no
  # landing, no card) — this is the "reviewer-agent ... scope-deferred
  # (no card)" half of R6, distinct from --pinned-landing's R3 (which
  # WIDENS the reviewer to run, never skips it). `autobuilder gate`'s own
  # reviewer-agent spec (crates/gate/src/lib.rs) requires the file be
  # PRESENT with `schema`/`head_sha`/`decision` — a missing file is read
  # as a hard block, same trap ci-checks' write_ci_defer_receipt above
  # already closes for its own producer — so this writes a synthetic
  # receipt rather than leaving the phase merely "skipped" the way an
  # ordinary main-scope run with a pre-existing block does a few lines
  # down (that path is safe only because SOME OTHER note already forces
  # the aggregate to block regardless; main-health has no such guarantee).
  reviewer_receipt="$project_abs/target/autobuilder/receipts/reviewer-agent.json"
  mkdir -p "$(dirname "$reviewer_receipt")" 2>/dev/null || true
  jq -n --arg head "$head_now" --arg captured "$(date -u +%Y-%m-%dT%H:%M:%SZ)" '{
    schema: "autobuilder.reviewer_agent_receipt.v1",
    head_sha: $head, intent_card_sha: "", decision: "pass",
    block_reasons: [], concern_reasons: [],
    scope_deferred: true, skip_reason: "main-health: no PRD/slug to review a range against",
    captured_at: $captured, receipt_digest: ""
  }' > "$reviewer_receipt" 2>/dev/null
  echo "extend-gate: reviewer-agent scope-deferred (main-health — no card)" >&2
  journal_line --file "$journal" "$(date -u +%FT%TZ)  gate  ${repo##*/}  reviewer-deferred  (main-health head=${head_now:0:7})"
  record_phase reviewer 0 defer
elif { [ "$scope" = branch ] && [ "$intent_card_stale" != true ]; } || [ "${#blocking_notes[@]}" -eq 0 ]; then
  run_reviewer || true
  # PRD-build-reviewer-receipt-primary R5: the note (and this phase's own
  # ok/fail) tracks run_reviewer()'s OWN $_reviewer_verdict — set from a
  # FRESH receipt or a balanced-decoded stdout object (never a stale
  # leftover re-read off disk, the 05:15:46Z misdiagnosis this replaces).
  case "$_reviewer_verdict" in
    block)
      note_block "$_reviewer_fail_note"
      record_phase reviewer $(( $(date +%s) - _phase_t0 )) fail
      ;;
    infra)
      # An infra failure (mechanism trouble, or no fresh receipt/stdout at
      # all) is never a verdict (R4) — no note_block, so it never joins
      # blocking_notes/GATES; it still shows up in the phase-timing line
      # (record_phase ... fail) so it is visible without being mistaken
      # for a reviewer block.
      echo "extend-gate: ${_reviewer_fail_note} (infra — not a verdict)" >&2
      record_phase reviewer $(( $(date +%s) - _phase_t0 )) fail
      # PRD-build-gate-infra-outcome R1/R8: write the missing receipt so
      # `autobuilder gate` never reads an absent reviewer-agent.json as a
      # block (the 2026-09-17 false-red root cause) — shaped exactly like
      # the main-health synthetic receipt above (decision: "pass",
      # scope_deferred: true), distinguished only by its `skip_reason`
      # prefix. R2 below is what turns this into `incomplete` (not a
      # silent pass), purely from note_infra's record, never from
      # re-reading this file.
      # AC12: a finalize-rejected verdict gets its own phase tag
      # ("reviewer-agent:finalize-rejected") distinct from plain
      # "reviewer-agent" — journal's infra= field then names the specific
      # sub-case, and the rejected object's own decision/block_reasons
      # ride along in the receipt so a real finding stays legible even
      # though this run's own verdict is `infra`, never `block`.
      _reviewer_infra_phase="reviewer-agent"
      [ "$_reviewer_infra_kind" = "finalize-rejected" ] && _reviewer_infra_phase="reviewer-agent:finalize-rejected"
      _reviewer_infra_receipt="$project_abs/target/autobuilder/receipts/reviewer-agent.json"
      mkdir -p "$(dirname "$_reviewer_infra_receipt")" 2>/dev/null || true
      jq -n --arg head "$head_now" --arg captured "$(date -u +%Y-%m-%dT%H:%M:%SZ)" \
            --arg reason "infra:${_reviewer_infra_phase}:${_reviewer_fail_note}" \
            --arg detail "${_reviewer_infra_detail}" \
            --argjson rejected "${_reviewer_rejected_verdict}" '{
        schema: "autobuilder.reviewer_agent_receipt.v1",
        head_sha: $head, intent_card_sha: "", decision: "pass",
        block_reasons: [], concern_reasons: [],
        scope_deferred: true, skip_reason: $reason, infra_detail: $detail,
        rejected_verdict: $rejected,
        captured_at: $captured, receipt_digest: ""
      }' > "$_reviewer_infra_receipt" 2>/dev/null
      note_infra "${_reviewer_infra_phase} — ${_reviewer_fail_note}"
      ;;
    *)
      record_phase reviewer $(( $(date +%s) - _phase_t0 )) ok
      ;;
  esac
else
  echo "extend-gate: reviewer skipped — ${#blocking_notes[@]} block(s) already recorded (no Sonnet spend on a red gate)"
  # Was a hardcoded ~/brain/journal path, ignoring EXTEND_GATE_JOURNAL and
  # the isolation-guard.sh default-deny sentinel every OTHER journal write
  # in this file already honors — the one write in this script that could
  # (and did) leak selftest fixture lines into the real shared journal.
  # Fixed in passing (PRD-build-gate-before-land requirement 7 found it via
  # the same isolation gap it was closing for select-guard.sh).
  journal_line --file "$journal" "$(date -u +%FT%TZ)  gate  ${repo##*/}  reviewer-skipped  (blocks=${#blocking_notes[@]} head=${head_now:0:7})"
  record_phase reviewer 0 skip
fi

# --- PRD-build-gate-route-parity-ledger requirement 1 (R1/AC1) ------------
# Stamp every producer receipt this run has written or refreshed so far
# with `"route": "<GATE_ROUTE>"` — one sweep, after every producer above
# (steps 1-8, including the 17 extended-receipts producers, all of which
# land in the same receipts/ dir) has had its chance to write/refresh its
# own receipt, and BEFORE the final `autobuilder gate` tally reads them
# fresh off disk. Never touches a producer's pass/fail verdict, never
# renames an existing key (Technical considerations) — jq's `.route = $r`
# only ever adds or overwrites this one key. A receipt jq can't parse (or
# a write that races a producer still holding the file) is skipped, not
# fatal — a missing route on one stale/malformed file is a --parity
# `route=unknown` line (Migration/compatibility), never a gate abort.
# PRD-build-gate-phase-timing's own invariant (that PRD's AC4: "the sum
# of phase seconds is within 5% of wall or the line carries
# unattributed:<s>") applies to every script second, this sweep included
# — it gets its own timed phase (record_phase below) rather than landing
# as silent unattributed time between "reviewer" and "gate".
_phase_t0=$(date +%s)
receipts_dir="$project_abs/target/autobuilder/receipts"
routed_n=0
receipts_total=0
if [ -d "$receipts_dir" ]; then
  for _rf in "$receipts_dir"/*.json; do
    [ -f "$_rf" ] || continue
    _rf_tmp="$(mktemp "${TMPDIR:-/tmp}/extend-gate-route-stamp.XXXXXX")"
    if jq --arg route "$GATE_ROUTE" '.route = $route' "$_rf" > "$_rf_tmp" 2>/dev/null; then
      mv "$_rf_tmp" "$_rf"
    else
      rm -f "$_rf_tmp" 2>/dev/null || true
    fi
    receipts_total=$((receipts_total + 1))
    case "$GATE_ROUTE" in burst:*) routed_n=$((routed_n + 1)) ;; esac
  done
fi
