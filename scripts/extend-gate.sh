# --- refuse a --head that doesn't match actual HEAD, before any producer
#     runs (AC3) --------------------------------------------------------
# PRD-build-cargo-route-precedence requirement 4: --head now accepts an
# abbreviated SHA — resolved via `git rev-parse --verify <arg>^{commit}`
# (the `^{commit}` peels a tag/other object down to its commit, and
# --verify makes an unresolvable ref a clean failure instead of printing
# git's own error text) and compared as FULL SHAs against $head_now,
# never as raw strings (a bare prefix compared string-wise against a full
# SHA would always "mismatch" even when it names the exact same commit).
# An unresolvable --head value refuses the same as a genuine mismatch —
# the caller gave a ref this repo doesn't have, which is exactly as
# unsafe to proceed on as one that names the wrong commit.
if [ -n "$head_want" ]; then
  head_want_resolved="$(git -C "$repo" rev-parse --verify "${head_want}^{commit}" 2>/dev/null || true)"
  if [ -z "$head_want_resolved" ]; then
    die 5 "refusing — HEAD is $head_now, --head asked for $head_want (does not resolve to a commit in $repo)"
  elif [ "$head_want_resolved" != "$head_now" ]; then
    die 5 "refusing — HEAD is $head_now, --head asked for $head_want_resolved (given as $head_want)"
  fi
fi

# --- verdict cache (PRD-build-gate-delta-baseline P1; TREE-keyed since
#     PRD-build-gate-before-land requirement 4) --------------------------
# Keyed on (TREE sha, this script's own sha256) rather than the commit sha
# — a branch merged onto an unchanged main produces a NEW commit (a
# `--no-ff` merge commit, or a fast-forward) whose TREE is identical to
# what the branch already gated at, so `land`/`integrate` (below) can copy
# the branch's last-verdict.json onto main's cache file under the same
# tree key and have the post-land main-scope run replay it as a cache hit
# instead of re-running all 25 producers. A sibling that landed in between
# gives a genuinely different tree, so that case is correctly a miss, not
# a regression. An edit to extend-gate.sh itself (a new producer, a
# bugfix) still always invalidates a stale cached verdict via
# script_sha256, unchanged. `--record-baseline` always runs the full
# sequence; `--force` always bypasses the cache. Checked here, after the
# (cheap) dirty-tree/head-mismatch refusals above, so those refusals still
# apply to a would-be cache hit exactly as they do to a full run.
# Migration: a last-verdict.json written before this PRD has no
# `tree_sha` key, so `cached_tree` reads empty and this is correctly a
# miss once — the first fresh run rewrites the file with the tree key.
self_hash="$(sha256sum "$0" 2>/dev/null | awk '{print $1}')"
cache_file="$project_abs/target/autobuilder/last-verdict.json"
# R4 seed-in: cache_file lives inside $repo, which for a pinned-landing
# call is a detached worktree that has never existed before this run — it
# never has a cache_file of its own to find. If the caller gave us a
# mirror and cache_file is genuinely absent (never overwrite a real,
# fresher cache_file the worktree somehow already had), copy the mirror
# in so the existing tree/hash-keyed cache-hit check right below sees it
# exactly as if this worktree had gated M before. A missing or unreadable
# mirror is a silent miss, same as no mirror at all — this is a
# performance optimization, never a correctness gate (same failure
# posture as gate_cache_transfer in worktree-extend.sh).
if [ -n "$verdict_cache_mirror" ] && [ ! -f "$cache_file" ] && [ -f "$verdict_cache_mirror" ] && jq -e . "$verdict_cache_mirror" >/dev/null 2>&1; then
  mkdir -p "$(dirname "$cache_file")" 2>/dev/null && cp "$verdict_cache_mirror" "$cache_file" 2>/dev/null || true
fi
if ! $record_baseline && ! $force && [ -f "$cache_file" ] && ! jq -e . "$cache_file" >/dev/null 2>&1; then
  # PRD-build-fail-loud-evidence-kept AC7: a genuinely CORRUPTED cache
  # (invalid JSON) is journaled and removed explicitly instead of falling
  # through the tree/hash checks below as an ordinary, silent miss — the
  # gate below still runs fresh either way, but now with a named cause
  # instead of an empty-verdict path nobody can explain afterward.
  journal_line --file "$journal" "$(printf '%s  gate  %s  verdict-cache  corrupt  (path=%s)' \
    "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$(basename "$repo")" "$cache_file")"
  rm -f "$cache_file" 2>/dev/null || true
fi
if ! $record_baseline && ! $force && [ -f "$cache_file" ]; then
  cached_tree="$(jq -r '.tree_sha // empty' "$cache_file" 2>/dev/null || true)"
  cached_hash="$(jq -r '.script_sha256 // empty' "$cache_file" 2>/dev/null || true)"
  # PRD-build-branch-gate-scope-artifacts requirement 5 (P0, AC7):
  # "a deferred verdict must not be reused at main scope — include scope
  # in the cache key" (Technical considerations) is deliberately NOT a
  # blanket scope check here — that would regress PRD-build-gate-before-
  # land requirement 4 / AC7b's already-shipped contract, where `land`
  # transfers a branch-scope cache entry (scope=branch, same tree) so a
  # post-land `--scope main` gate call CAN replay it as a cache hit
  # instead of re-running all 25 producers on an unchanged tree
  # (extend-gate-scope-selftest.sh / gate-verdict-tree-cache-selftest.sh
  # AC7b assert exactly this: 0 producer output after land) — that
  # contract is still exactly what every land WITHOUT a deferral should
  # get. The narrower, correct guard: a cached entry that itself carries
  # `deferred_receipts` (rollback-plan/ci-checks rewritten to pass on disk
  # at branch scope, never actually re-verified) is never a safe hit for
  # ANY scope, branch or main — the preconditions it deferred on (a real
  # tag, a pushed CI run) were never checked, so replaying it would let
  # `ship-tag.sh` tag a commit whose rollback-plan/ci-checks were never
  # actually green. A cache MISS here falls through to a full run, which
  # is exactly how a normal `--scope main` gate call already re-verifies
  # deferred producers for real (they hit the `scope != branch` producer
  # paths below, unchanged main-scope behavior, Non-goals) — "before any
  # tag is created" holds because ship-tag.sh only ever runs after that
  # gate call itself exits 0 (SKILL.md's rust-extend ship step).
  cached_deferred_n=0
  if [ -f "$cache_file" ]; then
    cached_deferred_n="$(jq -r '(.deferred_receipts // []) | length' "$cache_file" 2>/dev/null || echo 0)"
  fi
  # PRD-build-gate-infra-outcome R10 (P1): the same reasoning as the
  # deferred-receipts guard just above applies to a cached `incomplete`
  # verdict — it means a phase never actually ran (claude -p failed under
  # quota, a producer's binary was missing), not that this tree is known
  # green or known red. Replaying it would let a fixed quota limit / a
  # binary that's now back on $PATH keep reporting the SAME stale
  # incomplete forever instead of the next run actually trying again — a
  # cache MISS here falls through to a full run, same as the deferred case.
  cached_verdict_precheck=""
  if [ -f "$cache_file" ]; then
    cached_verdict_precheck="$(jq -r '.verdict // empty' "$cache_file" 2>/dev/null || true)"
  fi
  if [ -n "$cached_tree" ] && [ "$cached_tree" = "$tree_now" ] && [ -n "$cached_hash" ] && [ "$cached_hash" = "$self_hash" ] && [ "${cached_deferred_n:-0}" = "0" ] && [ "$cached_verdict_precheck" != "incomplete" ]; then
    cached_verdict="$(jq -r '.verdict // empty' "$cache_file" 2>/dev/null || true)"
    cached_rc="$(jq -r '.exit_code // empty' "$cache_file" 2>/dev/null || true)"
    if [ -n "$cached_verdict" ] && [ -n "$cached_rc" ]; then
      echo "extend-gate: verdict=$cached_verdict (cached)"
      # AC7: a cache hit journals `(cached tree=... from=...)` — `from`
      # names which scope actually produced this verdict (main, or a
      # branch's slug when `land` transferred it here), read back from
      # the cache entry's own `scope`/`slug` fields (requirement-4 write
      # below always sets them; a pre-this-PRD cache never gets here at
      # all since it has no tree_sha to match on).
      cached_from_scope="$(jq -r '.scope // "main"' "$cache_file" 2>/dev/null || echo main)"
      cached_from_slug="$(jq -r '.slug // empty' "$cache_file" 2>/dev/null || true)"
      _cache_crate_name="$(basename "$repo")"
      if [ -n "$cached_from_slug" ]; then
        journal_line --file "$journal" "$(printf '%s  gate  %s  %s  (cached tree=%s from=%s slug=%s)' \
          "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$_cache_crate_name" "$cached_verdict" "$tree_now" "$cached_from_scope" "$cached_from_slug")"
      else
        journal_line --file "$journal" "$(printf '%s  gate  %s  %s  (cached tree=%s from=%s)' \
          "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$_cache_crate_name" "$cached_verdict" "$tree_now" "$cached_from_scope")"
      fi
      # R4 persist-out: keep the mirror in sync on a cache-hit replay too
      # (not just a fresh write below) — best-effort, never affects the
      # verdict this run already computed above.
      if [ -n "$verdict_cache_mirror" ]; then
        mkdir -p "$(dirname "$verdict_cache_mirror")" 2>/dev/null && cp "$cache_file" "$verdict_cache_mirror" 2>/dev/null || true
      fi
      exit "$cached_rc"
    fi
  fi
fi

